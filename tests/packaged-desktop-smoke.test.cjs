const assert=require('assert');
const fs=require('fs');
const os=require('os');
const path=require('path');
const {_electron:electron}=require('playwright');
const executable=path.resolve(__dirname,'../release-1.2.1/win-unpacked/日迹.exe');
const isolatedProfile=fs.mkdtempSync(path.join(os.tmpdir(),'riji-packaged-smoke-'));
(async()=>{
  const app=await electron.launch({executablePath:executable,args:['--no-sandbox',`--user-data-dir=${isolatedProfile}`],env:{...process.env,APPDATA:isolatedProfile}});
  try{
    const page=await app.firstWindow();
    await page.waitForLoadState('domcontentloaded');
    await page.locator('header h1').waitFor();
    assert.strictEqual(await page.title(),'日迹');
    assert.strictEqual(await page.locator('header h1').textContent(),'日迹');
    await page.evaluate(()=>page('diary'));
    await page.locator('#desktopDiaryLock').waitFor({state:'visible'});
    assert.strictEqual(await page.locator('#diaryLockTitle').textContent(),'设置日记密码');
    assert.strictEqual(await page.locator('body.diary-lock-open').count(),1);
    await page.locator('#diaryNewPassword').fill('12345');
    await page.locator('#diaryConfirmPassword').fill('12345');
    await page.locator('#diaryLockActions button').first().click();
    assert.strictEqual(await page.locator('#diaryLockError').textContent(),'密码至少需要 6 位。');
    await page.locator('#diaryNewPassword').fill('123456');
    await page.locator('#diaryConfirmPassword').fill('123456');
    await page.locator('#diaryLockActions button').first().click();
    const recoveryCode=await page.locator('#diaryRecoveryCode').textContent();
    assert(recoveryCode.length>20);
    await page.locator('#diaryCodeSaved').check();
    await page.getByRole('button',{name:'完成并进入日记'}).click();
    await page.evaluate(()=>page('home'));
    await page.reload();
    await page.evaluate(()=>page('diary'));
    assert.strictEqual(await page.locator('#diaryLockTitle').textContent(),'解锁日记');
    await page.locator('#diaryPassword').fill('123456');
    await page.getByRole('button',{name:'解锁',exact:true}).click();
    await page.locator('#desktopDiaryLock').waitFor({state:'hidden'});
    await page.locator('[data-diary-subview="observation"]').click();
    await page.locator('#observationTitle').fill('打包启动测试');
    await page.locator('#observationText').fill('桌面版能够保存。');
    await page.locator('#toggleObservationAnalysis').click();
    await page.locator('#observationAnalysis').fill('分析也能保存。');
    await page.locator('#saveObservation').click();
    assert.strictEqual(await page.locator('.observation-analysis-badge').count(),0);
    assert.strictEqual(await page.locator('.writing-record-meta').count(),1);
    assert.strictEqual(await page.evaluate(()=>cloudSnapshot().observations[0].analysis),'分析也能保存。');
    assert.strictEqual(await page.locator('.observation-item-text').count(),0);
    const previousDate=await page.evaluate(async()=>{
      const created=new Date();created.setHours(10,0,0,0);
      notes.push({id:'smoke-note',date:localDay(created),createdAt:created.toISOString(),updatedAt:created.toISOString(),text:'时间编辑测试',images:[]});
      saveNotes();page('archive');await openArchiveNoteEditor(notes.find(note=>note.id==='smoke-note'));
      created.setDate(created.getDate()-1);
      document.querySelector('#editNoteCreatedAt input').value=noteLocalDateTime(created.toISOString());
      return localDay(created);
    });
    await page.locator('#saveNote').click();
    await page.locator('#noteModal').waitFor({state:'hidden'});
    assert.strictEqual(await page.evaluate(()=>notes.find(note=>note.id==='smoke-note').date),previousDate);
    await page.evaluate(()=>page('notesTimeline'));
    assert.strictEqual(await page.locator('.timeline-entry[data-note-id="smoke-note"]').count(),1);
    await page.evaluate(()=>page('archive'));
    await page.evaluate(()=>{diaries.push({id:'smoke-diary',date:localDay(new Date()),text:'保密测试正文'});saveDiaries();archive()});
    assert.strictEqual(await page.locator('.archive-note[data-diary-id="smoke-diary"]').count(),0);
    assert.strictEqual(await page.locator('#records .archive-heading').allTextContents().then(items=>items.some(s=>s.includes('· 日记'))),false);
    await page.evaluate(()=>{
      const stamp=new Date().toISOString();
      localStorage.setItem('phd-reference-library',JSON.stringify([{id:'smoke-reference',title:'打包参考文献',authors:'测试作者',year:'2026',summary:'参考文献分区测试'}]));
      localStorage.setItem('phd-manuscripts',JSON.stringify([{id:'smoke-manuscript',title:'打包文稿',category:'文献综述',status:'初稿',content:'文稿分区测试',createdAt:stamp,updatedAt:stamp}]));
      location.reload();
    });
    await page.waitForLoadState('domcontentloaded');
    await page.getByRole('button',{name:'档案'}).click();
    await page.getByRole('button',{name:'参考文献'}).click();
    assert.strictEqual(await page.locator('.reference-card').count(),1);
    assert.strictEqual((await page.locator('#records').textContent()).includes('复盘记录'),false);
    assert.strictEqual((await page.locator('body').textContent()).includes('当前为 iPhone 预览版'),false);
    assert.strictEqual(await page.evaluate(()=>cloudSnapshot().references.some(item=>item.id==='smoke-reference')),true);
    await page.getByRole('button',{name:'文稿',exact:true}).click();
    assert.strictEqual(await page.locator('.manuscript-card').count(),1);
    assert.strictEqual((await page.locator('#records').textContent()).includes('打包参考文献'),false);
    assert.strictEqual((await page.locator('body').textContent()).includes('iPhone 预览版'),false);
    assert.strictEqual(await page.evaluate(()=>cloudSnapshot().manuscripts.some(item=>item.id==='smoke-manuscript')),true);
    await page.getByRole('button',{name:'每日记录'}).click();
    await page.setViewportSize({width:496,height:720});
    await page.evaluate(()=>{
      const stamp=new Date().toISOString();
      notes.push({id:'smoke-long-note',date:day(),createdAt:stamp,updatedAt:stamp,text:Array.from({length:35},(_,index)=>`${index+1}. Anquez et al., 2019\nAutomatic correction and simplification of geological maps and cross-sections for numerical simulation\nImpacts of geometric model simplifications on wave propagation—application to ground motion simulation in the lower Var valley basin (France)`).join('\n\n'),images:[]});
      saveNotes();document.querySelector('#archiveDate').value=day();archive();
    });
    const longCard=page.locator('.archive-note[data-note-id="smoke-long-note"]');
    await longCard.locator('.archive-note-toggle').waitFor();
    await longCard.locator('.archive-note-toggle').click();
    const expandedRange=await page.evaluate(()=>{const main=document.querySelector('main');main.scrollTop=main.scrollHeight;return main.scrollHeight-main.clientHeight});
    await page.evaluate(()=>document.querySelector('main').scrollTop=0);
    await page.mouse.move(200,400);
    await page.mouse.wheel(0,100000);
    await page.waitForFunction(()=>{const main=document.querySelector('main');return Math.abs(main.scrollTop-(main.scrollHeight-main.clientHeight))<2});
    await longCard.locator('.archive-note-toggle').click();
    const collapsed=await page.evaluate(()=>{const main=document.querySelector('main');main.scrollTop=main.scrollHeight;return {range:main.scrollHeight-main.clientHeight,gap:main.getBoundingClientRect().bottom-[...document.querySelectorAll('#records > *')].at(-1).getBoundingClientRect().bottom,rootRange:document.documentElement.scrollHeight-innerHeight}});
    assert(expandedRange>collapsed.range,`packaged archive folding did not shorten scroll range: ${JSON.stringify({expandedRange,collapsed})}`);
    assert(collapsed.gap<90&&collapsed.rootRange<2,`packaged archive leaves scrollable blank space: ${JSON.stringify(collapsed)}`);
    await page.evaluate(()=>page('diary'));
    await page.locator('#diaryPassword').fill('wrong-password');
    await page.getByRole('button',{name:'解锁',exact:true}).click();
    assert.strictEqual(await page.locator('#desktopDiaryLock').isVisible(),true);
    await page.locator('#diaryPassword').fill('123456');
    await page.getByRole('button',{name:'解锁',exact:true}).click();
    await page.locator('#desktopDiaryLock').waitFor({state:'hidden'});
    await page.evaluate(()=>page('home'));
    await page.evaluate(()=>page('diary'));
    await page.getByRole('button',{name:'忘记密码'}).click();
    await page.locator('#diaryRecoveryInput').fill(recoveryCode);
    await page.locator('#diaryNewPassword').fill('54321');
    await page.locator('#diaryConfirmPassword').fill('54321');
    await page.getByRole('button',{name:'重设密码'}).click();
    assert.strictEqual(await page.locator('#diaryLockError').textContent(),'新密码至少需要 6 位。');
    await page.locator('#diaryNewPassword').fill('654321');
    await page.locator('#diaryConfirmPassword').fill('654321');
    await page.getByRole('button',{name:'重设密码'}).click();
    await page.locator('#diaryCodeSaved').check();
    await page.getByRole('button',{name:'完成并进入日记'}).click();
    await page.evaluate(()=>page('home'));
    await page.reload();
    await page.evaluate(()=>page('diary'));
    await page.locator('#diaryPassword').fill('654321');
    await page.getByRole('button',{name:'解锁',exact:true}).click();
    await page.locator('#desktopDiaryLock').waitFor({state:'hidden'});
    console.log('PACKAGED_DESKTOP_SMOKE_OK',executable);
  }finally{await app.close()}
})().catch(error=>{console.error(error);process.exitCode=1});
